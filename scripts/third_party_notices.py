#!/usr/bin/env python3
"""Writes THIRD-PARTY-NOTICES.md: every crate that is linked into the Windows or Linux build,
with its version, license and home page, from `cargo metadata`."""
import json, subprocess, sys

TARGETS = ["x86_64-pc-windows-msvc", "x86_64-unknown-linux-musl"]
crates = {}
for t in TARGETS:
    out = subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--locked", "--filter-platform", t],
        capture_output=True, text=True, check=True).stdout
    meta = json.loads(out)
    ws = set(meta["workspace_members"])
    # only crates that are normal (non-dev, non-build-only) dependencies of the shipped binaries
    resolve = {n["id"]: n for n in meta["resolve"]["nodes"]}
    roots = [i for i in ws if any(p["id"] == i and p["name"] in ("pasteroll-win", "pasteroll-linux") for p in meta["packages"])]
    seen, stack = set(), list(roots)
    while stack:
        i = stack.pop()
        if i in seen:
            continue
        seen.add(i)
        for d in resolve[i]["deps"]:
            if any(k["kind"] in (None, "build") for k in d["dep_kinds"]):
                stack.append(d["pkg"])
    for p in meta["packages"]:
        if p["id"] in seen and p["id"] not in ws:
            crates[(p["name"], p["version"])] = p

lines = ["# Third-party notices", "",
         "Pasteroll is built from the crates below. Each is used under the license shown; the full",
         "license text of every crate is in its source package (crates.io) and repository.", "",
         "Generated by `scripts/third_party_notices.py`.", "",
         "| Crate | Version | License | Home |", "|---|---|---|---|"]
for (name, ver), p in sorted(crates.items()):
    lic = (p.get("license") or p.get("license_file") or "see crate").replace("|", "/")
    home = p.get("repository") or p.get("homepage") or f"https://crates.io/crates/{name}"
    lines.append(f"| {name} | {ver} | {lic} | {home} |")
open("THIRD-PARTY-NOTICES.md", "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
print(len(crates), "crates")
